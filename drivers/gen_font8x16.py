#!/usr/bin/env python3
"""Regenerates drivers/font8x16.c from an 8x16 PSF1/PSF2 console font.

usage: gen_font8x16.py [font.psf[.gz]] > drivers/font8x16.c
Default font: Lat15-Terminus16 (Terminus, SIL Open Font License 1.1).
Only printable ASCII (0x20..0x7e) is emitted; the first 128 glyphs of the
Lat15 PSF files are plain ASCII.
"""
import gzip
import struct
import sys

DEFAULT = "/usr/share/consolefonts/Lat15-Terminus16.psf.gz"
FIRST, LAST = 0x20, 0x7e


def load(path):
    raw = open(path, "rb").read()
    if path.endswith(".gz"):
        raw = gzip.decompress(raw)
    if raw[:2] == b"\x36\x04":                 # PSF1
        charsize = raw[3]
        return raw[4:], charsize
    if raw[:4] == b"\x72\xb5\x4a\x86":         # PSF2
        (_, _, headersize, _, length, charsize, height, width) = \
            struct.unpack("<8I", raw[:32])
        if width != 8 or height != 16:
            raise SystemExit("font must be 8x16")
        return raw[headersize:], charsize
    raise SystemExit("not a PSF font")


def main():
    data, charsize = load(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
    if charsize != 16:
        raise SystemExit("font must be 8x16")
    out = ["/* Generated by gen_font8x16.py from Terminus 8x16 (Lat15-Terminus16).",
           " * Terminus Font is Copyright (C) Dimitar Zhekov, licensed under the",
           " * SIL Open Font License 1.1 (https://openfontlicense.org). */",
           '#include "fb.h"', "",
           "const uint8_t fb_font8x16[FB_FONT_GLYPHS][FB_FONT_HEIGHT] = {"]
    for code in range(FIRST, LAST + 1):
        glyph = data[code * 16:(code + 1) * 16]
        shown = chr(code) if chr(code) not in "\\*/" else "ch"
        out.append("    /* 0x%02x %s */ {%s}," % (
            code, shown, ", ".join("0x%02x" % b for b in glyph)))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
