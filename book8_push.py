#!/usr/bin/env python3
"""Push builds and configuration from this workstation to a running BOOK8.

Talks to the kernel's authenticated update agent (net/push.c, UDP 8081) and,
for FILE/KERNEL pushes, serves the payload from a one-shot TFTP server on this
machine (UDP 69). The shared HMAC key is build/push.key, generated by build.sh
and compiled into every kernel built from this tree.

Protocol (big-endian, "BK8P" v1): HELLO(client nonce) -> CHALLENGE(server
nonce, build id; HMAC binds the client nonce) -> COMMAND(HMAC over header and
136-byte body, server nonce) -> RESULT(HMAC). Commands are single-use: the
server nonce changes for every HELLO and expires after 10 s.

Examples (PowerShell, from the repository root):
  python book8_push.py --host 192.168.50.128 status
  python book8_push.py config --ip 192.168.50.208 --mask 255.255.255.0 \
      --gateway 192.168.50.1 --telemetry 192.168.50.17 --persist
  python book8_push.py file build\\user\\hello.elf --as HELLO.ELF
  python book8_push.py kernel --build          # build.ps1, push, relaunch, confirm
  python book8_push.py watch                   # rebuild + push on every source change
  python book8_push.py reboot

Lab use only: the key is embedded in the kernel image and TFTP is cleartext.
"""

import argparse
import hashlib
import hmac
import ipaddress
import os
import random
import re
import socket
import struct
import subprocess
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DEFAULT_HOST = "192.168.50.128"
PUSH_PORT = 8081
TFTP_PORT = 69
MAGIC = 0x424B3850
VERSION = 1
HELLO, CHALLENGE, COMMAND, RESULT = 1, 2, 3, 4
STATUS, CONFIG, FILE, KERNEL, REBOOT = 0, 1, 2, 3, 4
INSTALL_KERNEL = 5
COMMAND_NAMES = {STATUS: "STATUS", CONFIG: "CONFIG", FILE: "FILE", KERNEL: "KERNEL",
                 REBOOT: "REBOOT", INSTALL_KERNEL: "INSTALL_KERNEL"}
OK, ACCEPTED, BAD_REQUEST, BUSY, FAILED = 0, 1, 2, 3, 4
STATUS_NAMES = {OK: "OK", ACCEPTED: "ACCEPTED", BAD_REQUEST: "BAD_REQUEST", BUSY: "BUSY",
                FAILED: "FAILED"}
FLAG_PERSIST = 1

HEADER = struct.Struct("!IBBHI16s")           # 28 bytes
CHALLENGE_BODY = struct.Struct("!II")         # build_id, window_ms
COMMAND_BODY = struct.Struct("!BBHIIIII32s64s16s")  # 136 bytes
RESULT_BODY = struct.Struct("!BBHI96s")       # 104 bytes
MAC_BYTES = 32
NONCE_BYTES = 16
REMOTE_MAX, LOCAL_MAX, MESSAGE_MAX = 64, 16, 96
CHALLENGE_BYTES = HEADER.size + CHALLENGE_BODY.size + MAC_BYTES
COMMAND_BYTES = HEADER.size + COMMAND_BODY.size + MAC_BYTES
RESULT_BYTES = HEADER.size + RESULT_BODY.size + MAC_BYTES
assert (HEADER.size, COMMAND_BODY.size, RESULT_BODY.size) == (28, 136, 104)
assert (CHALLENGE_BYTES, COMMAND_BYTES, RESULT_BYTES) == (68, 196, 164)

MB2_MAGIC = 0xE85250D6
STAGE_CAPACITY = 8 * 1024 * 1024 - 64 * 1024   # kernel staging window minus relaunch plan
FILE_CAPACITY = 8 * 1024 * 1024


class PushError(Exception):
    pass


# ------------------------------------------------------------------ protocol

def load_key(path):
    try:
        text = Path(path).read_text(encoding="ascii").strip()
    except OSError as err:
        raise PushError(f"cannot read key {path}: {err} (run build.ps1 once to create it)")
    try:
        key = bytes.fromhex(text)
    except ValueError:
        key = b""
    if len(key) != 32:
        raise PushError(f"{path} must contain 64 hex digits")
    return key


def mac(key, data):
    return hmac.new(key, data, hashlib.sha256).digest()


def ip_to_int(text):
    return int(ipaddress.IPv4Address(text)) if text else 0


def int_to_ip(value):
    return str(ipaddress.IPv4Address(value))


def packet_header(kind, length, request_id, nonce):
    return HEADER.pack(MAGIC, VERSION, kind, length, request_id, nonce)


def build_hello(request_id, client_nonce):
    return packet_header(HELLO, 0, request_id, client_nonce)


def parse_challenge(key, data, request_id, client_nonce):
    """Returns (server_nonce, build_id, window_ms) or None if not a valid CHALLENGE."""
    if len(data) != CHALLENGE_BYTES:
        return None
    magic, version, kind, length, rid, nonce = HEADER.unpack_from(data)
    if (magic, version, kind, length, rid) != (MAGIC, VERSION, CHALLENGE,
                                               CHALLENGE_BODY.size, request_id):
        return None
    signed = data[:HEADER.size + CHALLENGE_BODY.size]
    if not hmac.compare_digest(mac(key, signed + client_nonce), data[len(signed):]):
        return None
    build_id, window_ms = CHALLENGE_BODY.unpack_from(data, HEADER.size)
    return nonce, build_id, window_ms


def _field(text, capacity, name):
    raw = text.encode("ascii") if text else b""
    if len(raw) >= capacity:
        raise PushError(f"{name} longer than {capacity - 1} characters")
    if any(b < 0x21 or b > 0x7E for b in raw):
        raise PushError(f"{name} must be printable ASCII without spaces")
    return raw.ljust(capacity, b"\0")


def build_command(key, request_id, server_nonce, command, *, flags=0, ip=0, mask=0,
                  gateway=0, telemetry=0, size=0, sha256=bytes(32), remote="", local=""):
    body = COMMAND_BODY.pack(command, flags, 0, ip, mask, gateway, telemetry, size, sha256,
                             _field(remote, REMOTE_MAX, "remote name"),
                             _field(local, LOCAL_MAX, "local name"))
    signed = packet_header(COMMAND, len(body), request_id, server_nonce) + body
    return signed + mac(key, signed)


def parse_result(key, data, request_id, nonces):
    """Returns the RESULT as a dict, or None if not a valid, authenticated RESULT."""
    if len(data) != RESULT_BYTES:
        return None
    magic, version, kind, length, rid, nonce = HEADER.unpack_from(data)
    if (magic, version, kind, length, rid) != (MAGIC, VERSION, RESULT, RESULT_BODY.size,
                                               request_id) or nonce not in nonces:
        return None
    signed = data[:HEADER.size + RESULT_BODY.size]
    if not hmac.compare_digest(mac(key, signed), data[len(signed):]):
        return None
    command, status, _reserved, build_id, message = RESULT_BODY.unpack_from(data, HEADER.size)
    return {"command": command, "status": status, "build_id": build_id,
            "message": message.split(b"\0", 1)[0].decode("ascii", "replace")}


class PushClient:
    def __init__(self, host, key, port=PUSH_PORT, verbose=True):
        self.host, self.key, self.port, self.verbose = host, key, port, verbose
        self.last_challenge = None

    def log(self, text):
        if self.verbose:
            print(text, flush=True)

    def run(self, command, result_timeout=15.0, hello_attempts=6, before_command=None,
            **fields):
        """Performs HELLO/CHALLENGE/COMMAND/RESULT and returns the RESULT dict."""
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            sock.bind(("0.0.0.0", 0))
            target = (self.host, self.port)
            challenge = None
            for attempt in range(hello_attempts):
                # Each HELLO replaces the agent's nonce, so a late CHALLENGE from an
                # earlier attempt must not be accepted: fresh id and nonce per attempt.
                request_id = random.getrandbits(32)
                client_nonce = os.urandom(NONCE_BYTES)
                sock.sendto(build_hello(request_id, client_nonce), target)
                challenge = self._wait(sock, 1.0 + attempt * 0.5,
                                       lambda d: parse_challenge(self.key, d, request_id,
                                                                 client_nonce),
                                       busy_nonces=(client_nonce,), request_id=request_id)
                if challenge:
                    break
            if challenge is None:
                raise PushError(f"no authenticated CHALLENGE from {self.host}:{self.port} "
                                "(BOOK8 offline, push agent not built, firewall, or a "
                                "different build/push.key)")
            if isinstance(challenge, dict):  # signed BUSY result
                raise PushError(f"agent busy: {challenge['message']}")
            server_nonce, build_id, window_ms = challenge
            self.last_challenge = {"build_id": build_id, "window_ms": window_ms}
            self.log(f"[*] {self.host} build {build_id}: challenge accepted, "
                     f"sending {COMMAND_NAMES.get(command, command)}")
            packet = build_command(self.key, request_id, server_nonce, command, **fields)
            if before_command:
                before_command()
            nonces = (server_nonce, client_nonce)
            deadline = time.monotonic() + result_timeout
            while time.monotonic() < deadline:
                sock.sendto(packet, target)  # identical retransmits are idempotent
                result = self._wait(sock, min(3.0, max(0.1, deadline - time.monotonic())),
                                    lambda d: parse_result(self.key, d, request_id, nonces))
                if result:
                    return result
            raise PushError(f"no RESULT within {result_timeout:g}s")
        finally:
            sock.close()

    def _wait(self, sock, seconds, parse, busy_nonces=(), request_id=None):
        deadline = time.monotonic() + seconds
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return None
            sock.settimeout(remaining)
            try:
                data, addr = sock.recvfrom(2048)
            except socket.timeout:
                return None
            except ConnectionResetError:
                # Windows reports ICMP port-unreachable as a reset on the next recv.
                continue
            if addr[0] != self.host:
                continue
            parsed = parse(data)
            if parsed:
                return parsed
            if busy_nonces:
                busy = parse_result(self.key, data, request_id, busy_nonces)
                if busy and busy["status"] == BUSY:
                    return busy


# ---------------------------------------------------------------------- TFTP

class OneShotTftpServer(threading.Thread):
    """Serves exactly one octet-mode RRQ for `name` from `allowed_ip`, then exits."""

    def __init__(self, name, data, bind="0.0.0.0", port=TFTP_PORT, allowed_ip=None,
                 timeout=1.0, retries=10, idle=120.0, verbose=True):
        super().__init__(daemon=True)
        self.name, self.data, self.allowed_ip = name, data, allowed_ip
        self.timeout, self.retries, self.idle, self.verbose = timeout, retries, idle, verbose
        self.bind_address = bind
        self.listen = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            self.listen.bind((bind, port))
        except OSError as err:
            self.listen.close()
            raise PushError(f"cannot bind TFTP UDP {bind}:{port}: {err} (another TFTP "
                            "server running? use --tftp-port only for tests)")
        self.port = self.listen.getsockname()[1]
        self.done = threading.Event()
        self.error = None
        self.blocks = self.retransmits = 0
        self._stop_event = threading.Event()

    def stop(self):
        self._stop_event.set()

    def log(self, text):
        if self.verbose:
            print(text, flush=True)

    def run(self):
        try:
            self._serve()
        except Exception as err:  # reported to the caller via .error
            self.error = str(err)
        finally:
            self.listen.close()
            self.done.set()

    def _serve(self):
        deadline = time.monotonic() + self.idle
        self.listen.settimeout(0.25)
        while not self._stop_event.is_set():
            if time.monotonic() > deadline:
                raise PushError("TFTP: no read request arrived")
            try:
                packet, client = self.listen.recvfrom(1024)
            except socket.timeout:
                continue
            except ConnectionResetError:
                continue
            if self.allowed_ip and client[0] != self.allowed_ip:
                continue
            if len(packet) < 4 or struct.unpack_from("!H", packet)[0] != 1:
                continue
            parts = packet[2:].split(b"\0")
            if len(parts) < 3:
                continue
            filename = parts[0].decode("ascii", "replace")
            mode = parts[1].decode("ascii", "replace").lower()
            with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as transfer:
                transfer.bind((self.bind_address, 0))
                if filename != self.name or mode != "octet":
                    transfer.sendto(struct.pack("!HH", 5, 1) + b"file not found\0", client)
                    self.log(f"[!] TFTP: refused RRQ {filename!r} mode {mode!r}")
                    continue
                self.log(f"[*] TFTP: {client[0]}:{client[1]} fetching {len(self.data)} bytes")
                self._transfer(transfer, client)
                return

    def _transfer(self, sock, client):
        total_blocks = len(self.data) // 512 + 1   # final block is short (maybe empty)
        sock.settimeout(self.timeout)
        for index in range(total_blocks):
            block = (index + 1) & 0xFFFF
            payload = struct.pack("!HH", 3, block) + self.data[index * 512:(index + 1) * 512]
            for attempt in range(self.retries + 1):
                if self._stop_event.is_set():
                    raise PushError("TFTP: stopped")
                if attempt:
                    self.retransmits += 1
                sock.sendto(payload, client)
                if self._await_ack(sock, client, block):
                    break
            else:
                raise PushError(f"TFTP: no ACK for block {block} after {self.retries} retries")
            self.blocks += 1

    def _await_ack(self, sock, client, block):
        deadline = time.monotonic() + self.timeout
        while time.monotonic() < deadline:
            try:
                packet, source = sock.recvfrom(1024)
            except socket.timeout:
                return False
            except ConnectionResetError:
                continue
            if source != client or len(packet) < 4:
                continue
            opcode, number = struct.unpack_from("!HH", packet)
            if opcode == 5:
                text = packet[4:].split(b"\0")[0].decode("ascii", "replace")
                raise PushError(f"TFTP: client error {number}: {text}")
            if opcode == 4 and number == block:
                return True
        return False


# -------------------------------------------------------------------- checks

def check_kernel_image(data):
    """Fails fast on images the kernel's relaunch validator would reject."""
    if len(data) > STAGE_CAPACITY:
        raise PushError(f"kernel is {len(data)} bytes; staging window is {STAGE_CAPACITY}")
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        raise PushError("kernel must be a little-endian ELF64 file")
    if struct.unpack_from("<H", data, 18)[0] != 0x3E:
        raise PushError("kernel ELF is not x86-64")
    for offset in range(0, min(len(data), 32768) - 15, 8):
        magic, arch, length, checksum = struct.unpack_from("<IIII", data, offset)
        if (magic == MB2_MAGIC and arch == 0 and length >= 16
                and (magic + arch + length + checksum) & 0xFFFFFFFF == 0):
            return
    raise PushError("no Multiboot2 header in the first 32 KiB (not a BOOK8 kernel)")


def valid_83(name):
    return re.fullmatch(r"[A-Z0-9_-]{1,8}(\.[A-Z0-9_-]{1,3})?", name) is not None


def report(result, prefix="BOOK8"):
    status = STATUS_NAMES.get(result["status"], str(result["status"]))
    print(f"[{'+' if result['status'] in (OK, ACCEPTED) else '!'}] {prefix} "
          f"{COMMAND_NAMES.get(result['command'], result['command'])} {status} "
          f"(build {result['build_id']}): {result['message']}", flush=True)
    return result["status"] in (OK, ACCEPTED)


def relaunch_count(message):
    match = re.search(r"relaunch (\d+)", message)
    return int(match.group(1)) if match else None


# ------------------------------------------------------------------ commands

def push_payload(client, args, command, data, local=""):
    remote = f"book8-{random.getrandbits(32):08x}.bin"
    server = OneShotTftpServer(remote, data, bind=args.tftp_bind, port=args.tftp_port,
                               allowed_ip=args.host, verbose=not args.quiet)
    server.start()
    try:
        result = client.run(command, result_timeout=args.result_timeout,
                            size=len(data), sha256=hashlib.sha256(data).digest(),
                            remote=remote, local=local)
    finally:
        server.stop()
        server.join(5)
    if server.error and result["status"] not in (OK, ACCEPTED):
        print(f"[!] {server.error}")
    elif server.blocks:
        print(f"[*] TFTP: sent {server.blocks} blocks ({server.retransmits} retransmits)")
    return result


def cmd_status(client, args):
    return report(client.run(STATUS))


def cmd_config(client, args):
    values = {"ip": ip_to_int(args.ip), "mask": ip_to_int(args.mask),
              "gateway": ip_to_int(args.gateway), "telemetry": ip_to_int(args.telemetry)}
    result = client.run(CONFIG, flags=FLAG_PERSIST if args.persist else 0, **values)
    ok = report(result)
    if ok and args.ip != args.host:
        print(f"[*] BOOK8 now answers on {args.ip}; use --host {args.ip} from now on")
    return ok


def cmd_file(client, args):
    path = Path(args.path)
    data = path.read_bytes()
    local = (args.as_name or path.name).upper()
    if not valid_83(local):
        raise PushError(f"destination {local!r} is not an 8.3 name (use --as NAME.EXT)")
    if not data or len(data) > FILE_CAPACITY:
        raise PushError(f"file must be 1..{FILE_CAPACITY} bytes")
    return report(push_payload(client, args, FILE, data, local=local))


def run_build():
    print("[*] building (QEMU suites skipped; run build.ps1 for full validation)", flush=True)
    env = dict(os.environ, BOOK8_SKIP_RING3_SMOKE="1")
    if os.name == "nt":
        command = ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                   str(ROOT / "build.ps1")]
    else:
        command = ["bash", str(ROOT / "build.sh")]
    completed = subprocess.run(command, cwd=ROOT, env=env)
    if completed.returncode != 0:
        raise PushError(f"build failed with exit code {completed.returncode}")


def expected_build_id(path):
    id_file = ROOT / "build" / "build-id.txt"
    if path.resolve() == (ROOT / "build" / "book8.elf").resolve() and id_file.exists():
        try:
            return int(id_file.read_text().strip())
        except ValueError:
            return None
    return None


def cmd_kernel(client, args):
    if getattr(args, "build", False):
        run_build()
    path = Path(args.path)
    data = path.read_bytes()
    check_kernel_image(data)
    before = client.run(STATUS)
    before_count = relaunch_count(before["message"])
    print(f"[*] running build {before['build_id']} (relaunch {before_count}); "
          f"pushing {path} ({len(data)} bytes)")
    result = push_payload(client, args, KERNEL, data)
    if not report(result) or args.no_wait:
        return result["status"] in (OK, ACCEPTED)
    expected = expected_build_id(path)
    deadline = time.monotonic() + args.wait
    time.sleep(2.0)
    while time.monotonic() < deadline:
        try:
            after = client.run(STATUS, hello_attempts=2)
        except PushError:
            time.sleep(1.0)
            continue
        count = relaunch_count(after["message"])
        if before_count is not None and count is not None and count > before_count:
            ok = expected is None or after["build_id"] == expected
            print(f"[{'+' if ok else '!'}] relaunched: build {after['build_id']}"
                  f"{'' if expected is None else f' (expected {expected})'}, relaunch {count}")
            return ok
        time.sleep(1.0)
    print(f"[!] no relaunched kernel answered within {args.wait:g}s")
    return False


def cmd_reboot(client, args):
    return report(client.run(REBOOT))

def cmd_install_kernel(client, args):
    if args.build:
        run_build()
    path = Path(args.path)
    data = path.read_bytes()
    check_kernel_image(data)
    if len(data) > 1024 * 1024:
        raise PushError("persistent kernel update is limited to 1 MiB")
    expected = expected_build_id(path)
    if args.reboot and expected is None:
        raise PushError("automatic cold-boot verification needs build/book8.elf and build-id.txt")
    before = client.run(STATUS)
    if before["status"] != OK or "boot-update=1" not in before["message"].split():
        raise PushError("target lacks persistent update support; warm-push the new kernel first")
    print("[*] persistent update: A:\\boot\\book8.elf only; BOOK8.CFG and GRUB unchanged",
          flush=True)
    result = push_payload(client, args, INSTALL_KERNEL, data)
    if not report(result) or result["status"] != OK:
        return False
    if not args.reboot:
        print("[+] persisted; running kernel unchanged (use reboot for cold-boot verification)")
        return True
    if not report(client.run(REBOOT)):
        return False
    time.sleep(3)
    deadline = time.monotonic() + args.wait
    while time.monotonic() < deadline:
        try:
            after = client.run(STATUS, hello_attempts=2)
        except PushError:
            time.sleep(1)
            continue
        if (after["status"] == OK and after["build_id"] == expected
                and relaunch_count(after["message"]) == 0):
            print(f"[+] cold boot confirmed: build {expected}, relaunch 0", flush=True)
            return True
        time.sleep(1)
    print("[!] persistent write succeeded, but expected cold boot was not confirmed")
    return False


SOURCE_DIRS = ("src", "drivers", "net", "kernel", "lib", "include", "fs", "user")


def source_snapshot():
    state = {}
    for directory in SOURCE_DIRS:
        for path in (ROOT / directory).rglob("*"):
            if path.suffix in (".c", ".h", ".S", ".ld") and path.is_file():
                state[path] = path.stat().st_mtime_ns
    for extra in ("linker.ld", "build.sh"):
        path = ROOT / extra
        if path.exists():
            state[path] = path.stat().st_mtime_ns
    return state


def cmd_watch(client, args):
    print(f"[*] watching {', '.join(SOURCE_DIRS)}; Ctrl+C to stop")
    snapshot = source_snapshot()
    try:
        while True:
            time.sleep(args.interval)
            current = source_snapshot()
            if current == snapshot:
                continue
            time.sleep(1.0)  # let editors finish writing
            snapshot = source_snapshot()
            changed = sorted(str(p.relative_to(ROOT)) for p in snapshot
                             if current.get(p) != snapshot.get(p) or p not in current)
            print(f"[*] change detected: {', '.join(changed[:5]) or 'files removed'}")
            try:
                args.build = True
                cmd_kernel(client, args)
            except PushError as err:
                print(f"[!] {err}")
            snapshot = source_snapshot()
    except KeyboardInterrupt:
        print("\n[*] watch stopped")
        return True


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--host", default=DEFAULT_HOST,
                        help=f"BOOK8 IP (last known DHCP lease {DEFAULT_HOST}; verify with NETSTAT)")
    parser.add_argument("--port", type=int, default=PUSH_PORT, help=argparse.SUPPRESS)
    parser.add_argument("--key", default=str(ROOT / "build" / "push.key"))
    parser.add_argument("--tftp-bind", default="0.0.0.0")
    parser.add_argument("--tftp-port", type=int, default=TFTP_PORT, help=argparse.SUPPRESS)
    parser.add_argument("--result-timeout", type=float, default=120.0,
                        help="seconds to wait for a FILE/KERNEL result (default 120)")
    parser.add_argument("--quiet", action="store_true")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("status", help="authenticated ping: build id, uptime, config source")
    config = sub.add_parser("config", help="set IPv4/telemetry configuration")
    config.add_argument("--ip", required=True)
    config.add_argument("--mask", required=True)
    config.add_argument("--gateway", default="0.0.0.0")
    config.add_argument("--telemetry", default="0.0.0.0",
                        help="telemetry target IP (0.0.0.0 disables)")
    config.add_argument("--persist", action="store_true",
                        help="save forced-static mode in A:\\BOOK8DHCP.CFG for subsequent boots")
    file_parser = sub.add_parser("file", help="copy a file to the root of A:")
    file_parser.add_argument("path")
    file_parser.add_argument("--as", dest="as_name", help="8.3 destination name")
    for name, help_text in (("kernel", "push a kernel ELF and relaunch it in RAM"),
                            ("watch", "rebuild and push the kernel on every source change")):
        p = sub.add_parser(name, help=help_text)
        p.add_argument("path", nargs="?", default=str(ROOT / "build" / "book8.elf"))
